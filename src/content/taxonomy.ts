// Situation taxonomy for Carian Situasi: what a learner's sentence is really about.
// Sayings are attached to these concepts in data/curated/semantics.json by reading each meaning.
//
// Cue grammar (see src/lib/semantic.ts):
//   'a b|c + d|e ! f'  (phrase "a b" or c) AND (d or e) AND NOT f
//   '3:...'            weight of the cue; the default is 2 and a concept needs 2 to count, so a `1:` cue
//                      alone never decides anything. That is how one word such as "kawan" stays harmless.
//   '~x'               x must be negated in the sentence ("tidak sombong"); a plain x must not be.
//   '=x'               exact word only, no affix matching.
export type ConceptGroup = 'hubungan' | 'perwatakan' | 'usaha' | 'pengajaran' | 'perasaan' | 'masyarakat';

export interface SituationConcept {
  id: string;
  group: ConceptGroup;
  /** What the situation is about; reads after "Situasi ini tentang". */
  label: string;
  /** Why a saying attached to this concept fits; states the shared idea, never the learner's words. */
  why: string;
  cues: string[];
  /** Shown with the results when the collection has no saying exactly about this. */
  nota?: string;
  /** Concepts this one overrides when both fire (the narrower reading wins). */
  overrides?: string[];
}

